def lane_document(**overrides: object) -> dict:
    """The document the launcher builds for one lane, with named overrides."""
    arguments: dict = {
        "worktree": WORKTREE,
        "lane_scratch": LANE_SCRATCH,
        "home": LANE_HOME,
        "runtime": LANE_RUNTIME,
        "lane_input": LANE_INPUT,
        "readable_files": (LANE_SETTINGS, EMPTY_MCP),
        "socket": SOCKET,
        "writable_worktree": False,
        "operator_home": OPERATOR_HOME,
        "denied_roots": (LAUNCH_ROOT,),
    }
    arguments.update(overrides)
    return document(**arguments)  # type: ignore[arg-type]


def dig(settings: dict, dotted: str) -> object:
    current: object = settings
    for part in dotted.split("."):
        if not isinstance(current, dict) or part not in current:
            return None
        current = current[part]
    return current


class PolicyDocumentTests(unittest.TestCase):
    """What the generated document says, before anything is written."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.tmp = Path(self._tmp.name)
        self.operator_home = OPERATOR_HOME
        self.socket = SOCKET
        self.document = lane_document()

    def test_the_sandbox_is_on_and_an_unavailable_one_is_fatal(self) -> None:
        self.assertIs(dig(self.document, "sandbox.enabled"), True)
        self.assertIs(dig(self.document, "sandbox.failIfUnavailable"), True)
        self.assertIs(dig(self.document, "sandbox.allowUnsandboxedCommands"), False)

    def test_there_is_no_escape_hatch(self) -> None:
        """No Apple Events, no excluded commands, no filesystem-disable, no extra dirs."""
        self.assertIs(dig(self.document, "sandbox.allowAppleEvents"), False)
        self.assertEqual(dig(self.document, "sandbox.excludedCommands"), [])
        self.assertIs(dig(self.document, "sandbox.filesystem.disabled"), False)
        self.assertEqual(dig(self.document, "permissions.additionalDirectories"), [])
        self.assertIs(dig(self.document, "enableAllProjectMcpServers"), False)
        self.assertEqual(dig(self.document, "enabledMcpjsonServers"), [])
        self.assertEqual(dig(self.document, "hooks"), {})

    def test_bash_network_defaults_are_closed(self) -> None:
        self.assertEqual(dig(self.document, "sandbox.network.allowedDomains"), [])
        self.assertEqual(dig(self.document, "sandbox.network.deniedDomains"), ["*"])
        self.assertIs(dig(self.document, "sandbox.network.allowLocalBinding"), False)

    def test_only_this_lanes_socket_is_reachable(self) -> None:
        self.assertEqual(
            dig(self.document, "sandbox.network.allowUnixSockets"), [self.socket]
        )

    def test_a_lane_with_no_channel_gets_no_socket(self) -> None:
        gate = lane_document(socket=None)
        self.assertEqual(dig(gate, "sandbox.network.allowUnixSockets"), [])

    def test_the_operator_home_and_its_credentials_are_denied(self) -> None:
        denied = dig(self.document, "sandbox.filesystem.denyRead")
        self.assertIn(self.operator_home, denied)
        for relative in (".ssh", ".gnupg", ".aws", ".config/gh", ".claude", ".netrc"):
            self.assertIn(f"{self.operator_home}/{relative}", denied)

    def test_the_only_root_inside_the_operator_home_is_the_lane_worktree(self) -> None:
        """A worktree may live under the operator's home; nothing else may."""
        for key in ("allowRead", "allowWrite"):
            for root in dig(self.document, f"sandbox.filesystem.{key}"):
                self.assertFalse(root.startswith(f"{self.operator_home}/"), root)
                self.assertNotEqual(root, self.operator_home)

    def test_reads_are_the_lane_worktree_its_own_material_and_trusted_runtimes(self) -> None:
        allowed = dig(self.document, "sandbox.filesystem.allowRead")
        for expected in (WORKTREE, LANE_SCRATCH, LANE_HOME, LANE_RUNTIME, LANE_INPUT):
            self.assertIn(expected, allowed)
        self.assertIn("/usr/lib", allowed)
        self.assertNotIn("/", allowed)
        # Never the launcher's shared scratch root, which holds every lane.
        self.assertNotIn(LAUNCH_ROOT, allowed)

    def test_writes_are_only_this_lanes_scratch_and_home(self) -> None:
        self.assertEqual(
            dig(self.document, "sandbox.filesystem.allowWrite"), [LANE_SCRATCH, LANE_HOME]
        )

    def test_a_reviewer_cannot_write_its_worktree_or_its_git_metadata(self) -> None:
        self.assertNotIn(WORKTREE, dig(self.document, "sandbox.filesystem.allowWrite"))
        self.assertIn(f"{WORKTREE}/.git", dig(self.document, "sandbox.filesystem.denyWrite"))

    def test_a_builder_may_write_its_worktree_but_never_its_git_metadata(self) -> None:
        builder = lane_document(writable_worktree=True)
        self.assertIn(WORKTREE, dig(builder, "sandbox.filesystem.allowWrite"))
        self.assertIn(f"{WORKTREE}/.git", dig(builder, "sandbox.filesystem.denyWrite"))
        self.assertTrue(decides(builder, WORKTREE, write=True))
        self.assertFalse(decides(builder, f"{WORKTREE}/.git", write=True))

    def test_every_tool_that_bypasses_the_bash_sandbox_is_denied(self) -> None:
        denied = dig(self.document, "permissions.deny")
        for tool in OUTSIDE_SANDBOX_TOOLS:
            self.assertIn(tool, denied)
        for tool in SANDBOXED_TOOLS:
            self.assertNotIn(tool, denied)

    def test_the_generated_document_passes_its_own_policy_check(self) -> None:
        assert_settings(
            self.document,
            source="memory",
            worktree=WORKTREE,
            socket=self.socket,
            operator_home=self.operator_home,
            writable_worktree=False,
            lane_writable=(LANE_SCRATCH, LANE_HOME),
            lane_readonly=(LANE_RUNTIME, LANE_INPUT, LANE_SETTINGS, EMPTY_MCP),
            denied_roots=(LAUNCH_ROOT,),
            foreign_paths=(OTHER_LANE, BROKER_HOME, BROKER_PAYLOAD),
        )


class WorktreeUnderTheOperatorHomeTests(unittest.TestCase):
    """Former-red (PAPI-90 item 1): a real checkout lives under the operator's home.

    ``~/projects/worktrees/<lane>`` is where a worktree actually is on the
    machine this runs on, and the previous policy refused *any* allowed root
    below the operator's home — so the production probe failed closed and no
    agent lane could launch at all. The home is still denied whole; exactly one
    path comes back inside it, and it is the worktree this lane was authorised
    for.
    """

    def setUp(self) -> None:
        self.home = "/Users/operator"
        self.worktree = "/Users/operator/projects/worktrees/lane"
        self.document = lane_document(worktree=self.worktree, operator_home=self.home)

    def test_the_operator_home_is_still_denied_for_reading(self) -> None:
        self.assertIn(self.home, dig(self.document, "sandbox.filesystem.denyRead"))

    def test_the_operator_home_is_never_denied_for_writing(self) -> None:
        """Former-red (live): a broad write denial takes the builder's worktree with it.

        ``~/projects/worktrees/<lane>`` is inside the operator's home, so a
        ``denyWrite`` on the home refused the builder its own checkout — the live
        probe reported ``Operation not permitted`` on all three of the writes that
        must succeed. The home stays denied for *reading*, where a nested
        allowance genuinely does reopen a path, and the credential directories
        carry their own exact write denials.
        """
        builder = lane_document(
            worktree=self.worktree, operator_home=self.home, writable_worktree=True
        )
        for settings in (self.document, builder):
            self.assertNotIn(self.home, dig(settings, "sandbox.filesystem.denyWrite"))
        self.assertTrue(decides(builder, self.worktree, write=True))
        self.assertTrue(decides(builder, LANE_SCRATCH, write=True))
        self.assertTrue(decides(builder, LANE_HOME, write=True))

    def test_each_credential_directory_carries_its_own_write_denial(self) -> None:
        denied = dig(self.document, "sandbox.filesystem.denyWrite")
        for relative in CREDENTIAL_HOME_SUBPATHS:
            self.assertIn(f"{self.home}/{relative}", denied)

    def test_a_real_worktree_under_the_operator_home_is_accepted(self) -> None:
        """The regression: this used to raise, and no lane could start."""
        assert_settings(
            self.document,
            source="memory",
            worktree=self.worktree,
            socket=SOCKET,
            operator_home=self.home,
            writable_worktree=False,
        )
        self.assertTrue(decides(self.document, self.worktree, write=False))
        self.assertTrue(decides(self.document, f"{self.worktree}/src/app.py", write=False))

    def test_a_builder_worktree_under_the_operator_home_stays_writable(self) -> None:
        builder = lane_document(
            worktree=self.worktree, operator_home=self.home, writable_worktree=True
        )
        assert_settings(
            builder,
            source="memory",
            worktree=self.worktree,
            socket=SOCKET,
            operator_home=self.home,
            writable_worktree=True,
        )
        self.assertTrue(decides(builder, f"{self.worktree}/src/app.py", write=True))

    def test_every_credential_directory_in_that_home_stays_denied(self) -> None:
        for relative in CREDENTIAL_HOME_SUBPATHS:
            path = f"{self.home}/{relative}"
            with self.subTest(path=path):
                self.assertFalse(decides(self.document, path, write=False))
                self.assertFalse(decides(self.document, path, write=True))
        for path in (
            f"{self.home}/.ssh/id_ed25519",
            f"{self.home}/Library/Keychains/login.keychain-db",
            f"{self.home}/.config/gh/hosts.yml",
        ):
            with self.subTest(path=path):
                self.assertFalse(decides(self.document, path, write=False))

    def test_an_unrelated_subpath_of_that_home_stays_denied(self) -> None:
        """Neighbouring directories are not reachable just because a sibling is."""
        for path in (
            self.home,
            f"{self.home}/Documents",
            f"{self.home}/projects",
            f"{self.home}/projects/worktrees",
            f"{self.home}/projects/worktrees/other-lane",
            f"{self.home}/projects/worktrees/lane-two",
        ):
            with self.subTest(path=path):
                self.assertFalse(decides(self.document, path, write=False))
                self.assertFalse(decides(self.document, path, write=True))

    def test_allowing_an_unrelated_home_subpath_is_still_refused(self) -> None:
        """Widening back to "anything under the home" fails validation."""
        loosened = json.loads(json.dumps(self.document))
        loosened["sandbox"]["filesystem"]["allowRead"].append(f"{self.home}/Documents")
        with self.assertRaises(LaunchPolicyError) as caught:
            assert_settings(
                loosened,
                source="memory",
                worktree=self.worktree,
                operator_home=self.home,
            )
        self.assertIn("operator's home", caught.exception.message)
        self.assertEqual(caught.exception.evidence["root"], f"{self.home}/Documents")

    def test_allowing_a_credential_directory_is_refused_even_as_the_worktree(self) -> None:
        """A lane cannot be authorised for ``~/.ssh`` by calling it a worktree."""
        credential = f"{self.home}/.ssh"
        loosened = lane_document(worktree=credential, operator_home=self.home)
        with self.assertRaises(LaunchPolicyError) as caught:
            assert_settings(
                loosened, source="memory", worktree=credential, operator_home=self.home
            )
        self.assertIn("credential directory", caught.exception.message)


class LaneScopedMaterialTests(unittest.TestCase):
    """Former-red (PAPI-90 item 2): the launcher's scratch root is not a lane's.

    The document used to allow the whole :class:`~.launchers.LaunchBroker`
    scratch for read *and* write. That root holds every lane's runtime, every
    lane's synthetic home, every lane's settings file, the empty MCP config, and
    the capability broker's own request payloads — so a surviving descendant of
    lane A could rewrite the shim, the policy, or the home that lane B would
    later be launched with. Mode bits are not the answer: those files are owned
    by the same user the lane runs as, and that user can put a write bit back.

    So the root is denied and the lane's own two directories are allowed back
    inside it. Every assertion below is about a concrete path.
    """

    def setUp(self) -> None:
        self.document = lane_document()
        self.builder = lane_document(writable_worktree=True)

    def denied(self, path: str, *, document: dict | None = None) -> None:
        settings = self.document if document is None else document
        self.assertFalse(decides(settings, path, write=False), f"readable: {path}")
        self.assertFalse(decides(settings, path, write=True), f"writable: {path}")

    def readable_not_writable(self, path: str) -> None:
        self.assertTrue(decides(self.document, path, write=False), f"unreadable: {path}")
        self.assertFalse(decides(self.document, path, write=True), f"writable: {path}")

    def test_the_launcher_scratch_root_is_denied_for_reading(self) -> None:
        self.assertIn(LAUNCH_ROOT, dig(self.document, "sandbox.filesystem.denyRead"))
        self.denied(LAUNCH_ROOT)
        self.denied("/scratch/lanes")

    def test_the_launcher_scratch_root_is_never_denied_for_writing(self) -> None:
        """Former-red (live): a broad write denial takes the lane's own roots with it.

        This lane's scratch and synthetic home are *inside* the launcher's
        scratch root. A ``denyWrite`` on the root is absolute in this client, so
        naming it there denied the lane the two directories it exists to write —
        which is exactly what the live probe reported. Sibling lanes stay
        unwritable for a different reason: none of them is the working directory
        and none is an ``allowWrite`` root.
        """
        self.assertNotIn(LAUNCH_ROOT, dig(self.document, "sandbox.filesystem.denyWrite"))
        self.assertTrue(decides(self.document, LANE_SCRATCH, write=True))
        self.assertTrue(decides(self.document, LANE_HOME, write=True))
        self.assertFalse(decides(self.document, LAUNCH_ROOT, write=True))
        self.assertFalse(decides(self.document, OTHER_LANE, write=True))

    def test_the_lane_owns_its_scratch_and_home_and_nothing_wider(self) -> None:
        for path in (LANE_SCRATCH, LANE_TMP, LANE_HOME, f"{LANE_HOME}/.cache/thing"):
            with self.subTest(path=path):
                self.assertTrue(decides(self.document, path, write=False))
                self.assertTrue(decides(self.document, path, write=True))

    def test_the_lane_cannot_write_its_own_runtime_or_shim(self) -> None:
        """The shim the lane runs is readable, and replaceable by nobody."""
        self.readable_not_writable(LANE_RUNTIME)
        self.readable_not_writable(LANE_SHIM)

    def test_the_lane_cannot_write_its_own_settings_file(self) -> None:
        self.readable_not_writable(LANE_SETTINGS)

    def test_the_lane_cannot_write_its_own_frozen_input(self) -> None:
        self.readable_not_writable(LANE_INPUT)
        self.readable_not_writable(LANE_PACKET)

    def test_the_lane_cannot_write_the_empty_mcp_config(self) -> None:
        self.readable_not_writable(EMPTY_MCP)

    def test_the_brokers_own_material_is_out_of_reach(self) -> None:
        """The broker acts with a real credential; no lane reads where it works."""
        self.denied(BROKER_HOME)
        self.denied(f"{BROKER_HOME}/.config/gh/hosts.yml")
        self.denied(BROKER_PAYLOAD)

    def test_another_lane_is_out_of_reach_entirely(self) -> None:
        for path in (
            OTHER_LANE,
            f"{OTHER_LANE}/home",
            f"{OTHER_LANE}/home/.gitconfig",
            f"{OTHER_LANE}/scratch",
            f"{OTHER_LANE}/scratch/tmp/work",
            f"{OTHER_LANE}/runtime/002-other/bin/claude-broker",
            f"{OTHER_LANE}/settings.json",
            f"{OTHER_LANE}/input/blockers.json",
        ):
            with self.subTest(path=path):
                self.denied(path)

    def test_an_os_temp_path_is_not_a_way_back_in(self) -> None:
        """The same layout under a real OS temp root behaves the same way."""
        root = "/var/folders/xx/T/pr-prover-launch-abc"
        lane = f"{root}/lanes/001-lane"
        settings = document(
            worktree=WORKTREE,
            lane_scratch=f"{lane}/scratch",
            home=f"{lane}/home",
            runtime=f"{lane}/runtime/001-lane",
            lane_input=f"{lane}/input",
            readable_files=(f"{lane}/settings.json", f"{root}/mcp-empty.json"),
            socket=SOCKET,
            writable_worktree=True,
            operator_home=OPERATOR_HOME,
            denied_roots=(root, "/var/folders/xx/T/pr-prover-scratch"),
        )
        self.assertTrue(decides(settings, f"{lane}/scratch/tmp/x", write=True))
        for path in (
            root,
            f"{root}/mcp-empty.json",
            f"{root}/lanes/002-other/home",
            f"{lane}/runtime/001-lane/bin/claude-broker",
            f"{lane}/settings.json",
            "/var/folders/xx/T/pr-prover-scratch/pr-prover-7-xyz/blockers-attempt1.json",
        ):
            with self.subTest(path=path):
                self.assertFalse(decides(settings, path, write=True), path)

    def test_the_builder_worktree_is_still_usable(self) -> None:
        """Denying everything shared must not cost the lane the work it came to do."""
        self.assertTrue(decides(self.builder, WORKTREE, write=False))
        self.assertTrue(decides(self.builder, f"{WORKTREE}/src/app.py", write=True))
        self.assertTrue(decides(self.builder, f"{LANE}/scratch/tmp/build.log", write=True))

    def test_validation_refuses_a_document_that_shares_the_scratch_root_again(self) -> None:
        """Former-red: the exact shape this repair removed no longer validates."""
        shared = document(
            worktree=WORKTREE,
            lane_scratch=LAUNCH_ROOT,
            home=LANE_HOME,
            runtime=LANE_RUNTIME,
            lane_input=LANE_INPUT,
            readable_files=(LANE_SETTINGS, EMPTY_MCP),
            socket=SOCKET,
            writable_worktree=False,
            operator_home=OPERATOR_HOME,
            denied_roots=(),
        )
        self.assertTrue(decides(shared, OTHER_LANE, write=True))
        with self.assertRaises(LaunchPolicyError) as caught:
            assert_settings(
                shared,
                source="memory",
                worktree=WORKTREE,
                socket=SOCKET,
                operator_home=OPERATOR_HOME,
                writable_worktree=False,
                denied_roots=(LAUNCH_ROOT,),
                foreign_paths=(OTHER_LANE, EMPTY_MCP),
            )
        self.assertIn("scratch root", caught.exception.message)

    def test_naming_a_read_only_root_in_allow_write_is_refused_as_contradictory(self) -> None:
        """A write denial outranks any allowance, so naming both is a bug, not a policy."""
        for root in (LANE_RUNTIME, LANE_SETTINGS, LANE_INPUT):
            loosened = json.loads(json.dumps(self.document))
            loosened["sandbox"]["filesystem"]["allowWrite"].append(root)
            with self.subTest(root=root):
                # The allowance buys nothing: the denial is absolute.
                self.assertFalse(decides(loosened, root, write=True))
                with self.assertRaises(LaunchPolicyError) as caught:
                    assert_settings(loosened, source="memory")
                self.assertEqual(caught.exception.evidence["allowWrite"], root)

    def test_validation_refuses_a_writable_runtime_or_settings_file(self) -> None:
        for root in (LANE_RUNTIME, LANE_SETTINGS, LANE_INPUT):
            loosened = json.loads(json.dumps(self.document))
            loosened["sandbox"]["filesystem"]["allowWrite"].append(root)
            loosened["sandbox"]["filesystem"]["denyWrite"] = [
                entry
                for entry in loosened["sandbox"]["filesystem"]["denyWrite"]
                if entry != root
            ]
            with self.subTest(root=root), self.assertRaises(LaunchPolicyError) as caught:
                assert_settings(
                    loosened,
                    source="memory",
                    lane_readonly=(LANE_RUNTIME, LANE_SETTINGS, LANE_INPUT),
                )
            self.assertIn("mode bits do not keep", caught.exception.message)

    def test_validation_refuses_a_document_that_reaches_a_sibling_lane(self) -> None:
        loosened = json.loads(json.dumps(self.document))
        loosened["sandbox"]["filesystem"]["allowRead"].append(OTHER_LANE)
        with self.assertRaises(LaunchPolicyError) as caught:
            assert_settings(loosened, source="memory", foreign_paths=(OTHER_LANE,))
        self.assertIn("not this lane's", caught.exception.message)

    def test_validation_refuses_a_lane_that_cannot_reach_its_own_scratch(self) -> None:
        loosened = json.loads(json.dumps(self.document))
        loosened["sandbox"]["filesystem"]["allowWrite"] = [LANE_HOME]
        with self.assertRaises(LaunchPolicyError):
            assert_settings(
                loosened, source="memory", lane_writable=(LANE_SCRATCH, LANE_HOME)
            )


class WriteBoundaryTests(unittest.TestCase):
    """Former-red (live probe, Claude Code 2.1.219): writes do not nest.

    Hermes generated this exact policy for a disposable builder worktree under
    ``/Users/creator/projects/worktrees``, handed it to a real client through
    ``--settings`` with ``--setting-sources ''``, strict MCP, Bash only, and
    ``allowUnsandboxedCommands=false``, and ran a live shell in it. Every denial
    held. So did three that must not: the builder's own worktree, the lane's own
    scratch, and the lane's own synthetic home were all refused with
    ``Operation not permitted``, because both were inside a region this document
    had broadly denied for writing and a nested ``allowWrite`` does not reopen
    one.

    Reads are not like that — a broad ``denyRead`` plus a specific ``allowRead``
    is documented and was confirmed live — so the two are modelled separately
    here and everywhere else.
    """

    def setUp(self) -> None:
        self.home = "/Users/operator"
