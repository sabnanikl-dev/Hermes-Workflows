class RecordingRunner:
    def __init__(self) -> None:
        self.calls: list[dict] = []

    def run(self, argv, *, cwd=None, env=None, timeout=None):  # type: ignore[no-untyped-def]
        self.calls.append({"argv": tuple(argv), "env": dict(env or {}), "cwd": cwd})
        return CommandResult(argv=tuple(argv), returncode=0, stdout="done\n", stderr="")

    @property
    def last(self) -> dict:
        return self.calls[-1]


class LaunchedSandboxTests(unittest.TestCase):
    """What an actual agent launch carries."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.tmp = Path(self._tmp.name)
        self.config = make_config(self.tmp, source_repo=make_source_repo(self.tmp))
        self.worktree = self.config.worktree_root / "attempt1"
        self.worktree.mkdir(parents=True)
        self.runner = RecordingRunner()
        self.lane_bin = lane_bin(self.tmp)
        self.operator_home = self.tmp / "operator-home"
        self.operator_home.mkdir()
        self.blockers = self.tmp / "blockers.json"
        self.blockers.write_text('{"blockers": []}\n', encoding="utf-8")
        self.broker = make_broker(
            self.config,
            self.runner,
            scratch_root=self.tmp,
            env=parent_env(
                HOME=str(self.operator_home), PATH=f"{self.lane_bin}:/usr/bin:/bin"
            ),
        )
        self.addCleanup(self.broker.close)

    def launch_reviewer(self) -> tuple[str, ...]:
        self.broker.run_reviewer(
            role="A", identity="reviewer", agent=AGENT, argv=None,
            bound=BOUND, cwd=self.worktree, timeout=None,
        )
        return self.runner.last["argv"]

    def launch_builder(self) -> tuple[str, ...]:
        self.broker.run_builder(
            identity="builder", agent=AGENT, argv=None, bound=BOUND,
            cwd=self.worktree, timeout=None, attempt=1, mode="initial",
            blockers_file=self.blockers,
            signature="Fixed by: a signature long enough",
        )
        return self.runner.last["argv"]

    def settings_of(self, argv: tuple[str, ...]) -> dict:
        return json.loads(
            Path(argv[argv.index("--settings") + 1]).read_text(encoding="utf-8")
        )

    def test_an_agent_lane_carries_a_launcher_owned_settings_file(self) -> None:
        argv = self.launch_reviewer()
        self.assertIn("--settings", argv)
        path = Path(argv[argv.index("--settings") + 1])
        self.assertTrue(path.is_absolute())
        assert_settings(self.settings_of(argv), source=str(path))

    def test_an_agent_lane_reads_no_settings_source_at_all(self) -> None:
        """Neither the operator's settings nor a .claude directory the PR added."""
        self.assertIn(SETTING_SOURCES_ENTRY, self.launch_reviewer())

    def test_the_settings_allow_exactly_this_lanes_capability_socket(self) -> None:
        argv = self.launch_reviewer()
        sockets = dig(self.settings_of(argv), "sandbox.network.allowUnixSockets")
        self.assertEqual(len(sockets), 1)
        self.assertEqual(sockets[0], self.runner.last["env"]["PR_PROVER_CAPABILITY_SOCKET"])

    def test_the_settings_deny_the_operator_home_of_this_run(self) -> None:
        argv = self.launch_reviewer()
        denied = dig(self.settings_of(argv), "sandbox.filesystem.denyRead")
        self.assertIn(str(self.operator_home), denied)

    def test_a_reviewer_worktree_is_read_only_and_a_builders_is_not(self) -> None:
        reviewer = self.settings_of(self.launch_reviewer())
        builder = self.settings_of(self.launch_builder())
        tree = str(self.worktree)
        self.assertNotIn(tree, dig(reviewer, "sandbox.filesystem.allowWrite"))
        self.assertIn(tree, dig(reviewer, "sandbox.filesystem.allowRead"))
        self.assertIn(tree, dig(builder, "sandbox.filesystem.allowWrite"))
        for settings in (reviewer, builder):
            self.assertIn(f"{tree}/.git", dig(settings, "sandbox.filesystem.denyWrite"))

    def test_every_launch_gets_a_fresh_settings_file(self) -> None:
        first = self.launch_reviewer()
        second = self.launch_builder()
        self.assertNotEqual(
            first[first.index("--settings") + 1], second[second.index("--settings") + 1]
        )

    def test_the_lane_environment_scrubs_its_subprocesses(self) -> None:
        """A lane's own shells must not re-export its capability secret."""
        self.launch_reviewer()
        env = self.runner.last["env"]
        self.assertEqual(env[SUBPROCESS_ENV_SCRUB], ENV_SCRUB_VALUE)
        self.assertIn(CAPABILITY_SECRET, env)


